function tr(message) {
  if (uiLanguage !== 'en') return message;
  const source = String(message);
  const key = source.replace(/\s+/g, ' ').trim();
  return UI_EN[key] ? source.replace(source.trim(), UI_EN[key]) : source;
}
function translateUIFragment(source) {
  if (uiLanguage !== 'en') return source;
  const tokens = [];
  const canonical = source.replace(/\uE100(\d+)\uE101/g, token => `{${tokens.push(token) - 1}}`);
  const key = canonical.replace(/\s+/g, ' ').trim();
  if (Object.hasOwn(UI_EN, key)) {
    const translated = UI_EN[key].replace(/\{(\d+)\}/g, (_, index) => tokens[Number(index)] ?? '');
    return source.match(/^\s*/)[0] + translated + source.match(/\s*$/)[0];
  }
  // Translate only literal UI fragments. Interpolated user data stays opaque.
  return source.split(/(\uE100\d+\uE101)/).map(part => /\uE100/.test(part) ? part : tr(part)).join('');
}
function uiText(strings, ...values) {
  const source = strings.reduce((result, part, index) => result + (index ? `\uE100${index - 1}\uE101` : '') + part, '');
  return translateUIFragment(source).replace(/\uE100(\d+)\uE101/g, (_, i) => String(values[Number(i)] ?? ''));
}
function uiHTML(strings, ...values) {
  if (uiLanguage !== 'en') return strings.reduce((result, part, index) => result + (index ? String(values[index - 1]) : '') + part, '');
  const source = strings.reduce((result, part, index) => result + (index ? `\uE100${index - 1}\uE101` : '') + part, '');
  const translated = source
    .replace(/(^|>)([^<>]*)(?=<|$)/g, (_, open, text) => open + translateUIFragment(text))
    .replace(/\b(title|placeholder|aria-label)="([^"]*)"/g, (_, name, value) => `${name}="${translateUIFragment(value)}"`);
  return translated.replace(/\uE100(\d+)\uE101/g, (_, i) => String(values[Number(i)]));
}
